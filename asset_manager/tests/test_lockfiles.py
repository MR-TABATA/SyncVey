def test_yarn_lock_v1_takes_registry_entries_only():
    eco, found, skipped = parse('yarn.lock', YARN_V1)
    assert eco == 'npm'
    # 同じ版を指す複数の範囲は 1 件。別名・GitHub・file は、registry の版と一致しないので拾わない
    assert found == [('@scope/example-ui', '2.1.4'), ('example-core', '1.0.7')]
    assert skipped == 3


def test_yarn_lock_berry_reads_resolution_and_resolves_aliases():
    eco, found, skipped = parse('sub/dir/yarn.lock', YARN_BERRY)
    assert eco == 'npm'
    # 別名（example-alias）は、実体の other-pkg として数える。workspace と patch は拾わない
    assert found == [('@scope/example-ui', '2.1.4'), ('example-core', '1.0.7'), ('other-pkg', '3.0.1')]
    assert skipped == 2


def test_yarn_lock_berry_ignores_a_dependency_named_resolution():
    raw = b"""__metadata:
  version: 8

"example-core@npm:^1.0.0":
  version: 1.0.7
  resolution: "example-core@npm:1.0.7"
  dependencies:
    resolution: "npm:^9.9.9"
"""
    assert parse('yarn.lock', raw)[1] == [('example-core', '1.0.7')]


def test_poetry_lock_skips_non_table_packages_and_non_string_versions():
    # package の要素が表でない（.get で AttributeError にならない）／version が文字列でない
    eco, found, skipped = parse('poetry.lock', b'package = ["x", 1]\n')
    assert (eco, found, skipped) == ('PyPI', [], 2)
    raw = b'[[package]]\nname = "a"\nversion = 1\n\n[[package]]\nname = "b"\nversion = "2.0"\n'
    assert parse('poetry.lock', raw)[1:] == ([('b', '2.0')], 1)


def test_yarn_lock_v1_skips_every_non_registry_range():
    for rng in ('someone/repo', 'git+ssh://example.invalid/x.git', 'link:../x', 'https://example.invalid/x.tgz', 'file:../x'):
        raw = f'# yarn lockfile v1\n\n\n"short@{rng}":\n  version "0.0.1"\n'.encode()
        assert parse('yarn.lock', raw)[1:] == ([], 1), rng


def test_yarn_lock_v1_skips_blocks_without_a_version_or_with_mixed_names():
    no_version = b'# yarn lockfile v1\n\n\nfoo@^1.0.0:\n  resolved "https://example.invalid/foo.tgz"\n'
    assert parse('yarn.lock', no_version)[1:] == ([], 1)
    mixed = b'# yarn lockfile v1\n\n\n"a@^1", "b@^1":\n  version "1.0.0"\n'     # 別のパッケージが 1 つの版を共有することは無い
    assert parse('yarn.lock', mixed)[1:] == ([], 1)


def test_yarn_lock_berry_skips_alias_in_resolution_and_non_numeric_versions():
    raw = b"""__metadata:
  version: 8

"foo@npm:^1.0.0":
  version: 1.0.0
  resolution: "foo@npm:bar@1.0.0"

"baz@npm:latest":
  version: 2.0.0
  resolution: "baz@npm:latest"

"ok@npm:^3.0.0":
  version: 3.0.0
  resolution: "ok@npm:3.0.0"
"""
    assert parse('yarn.lock', raw)[1:] == ([('ok', '3.0.0')], 2)


@pytest.mark.parametrize('name', ['poetry.lock', 'package-lock.json', 'composer.lock'])
def test_deeply_nested_input_is_a_clean_error_not_a_recursion_error(name):
    deep = b'x = ' + b'[' * 100000 + b']' * 100000 if name == 'poetry.lock' else b'[' * 100000 + b']' * 100000
    with pytest.raises(LockfileError):
        parse(name, deep)


@pytest.mark.parametrize('name,raw', [
    ('package-lock.json', b'not json'),
    ('package-lock.json', b'[]'),
    ('Dockerfile', b'FROM python'),
    ('poetry.lock', b'not toml ='),
    ('poetry.lock', b'name = "no-packages-table"'),
    ('yarn.lock', b'just some text'),
    ('requirements.txt', b'\xff\xfe\x00bad'),
    ('requirements.txt', b'x' * (5 * 1024 * 1024 + 1)),
])
def test_bad_input_is_a_clean_error(name, raw):
    with pytest.raises(LockfileError):
        parse(name, raw)
